import {test,expect} from "@playwright/test";
test("Win7 base tray shares Action Center, live network, battery and volume",async({page,context})=>{
  await page.addInitScript(()=>{
    const battery=Object.assign(new EventTarget(),{level:.73,charging:false});
    Object.defineProperty(navigator,"getBattery",{configurable:true,value:()=>Promise.resolve(battery)});
    Object.assign(window,{__sourceTestBattery:battery});
  });
  await page.goto("/?theme=win7");
  await page.locator('[data-test-avatar="win7"]').click({timeout:12000});
  const shell=page.locator("[data-test-main-screen]");
  const tray=shell.locator('[data-test-taskbar-tray="win7"]');
  const center=tray.locator("[data-test-action-center]");
  await center.click();
  const summary=tray.locator("[data-test-action-center-popup]");
  await expect(summary).toBeVisible();
  await expect(summary.locator("[data-test-notification-summary]")).toHaveText("No new messages");
  await expect(summary).toHaveCSS("border-top-left-radius","7px");
  await expect(summary).toHaveCSS("border-top-color","rgb(0, 0, 0)");
  await expect(summary).toHaveCSS("background-image",/linear-gradient/);
  const network=tray.locator("[data-test-network]");
  await network.press("Enter");
  await expect(summary).toHaveCount(0);
  const net=tray.locator("[data-test-network-popup]");
  await expect(net).toBeVisible();
  try{
    await context.setOffline(true);
    await expect(network.locator("img")).toHaveAttribute("src",/network-off/);
    await expect(net.getByRole("status")).toContainText("Browser reports offline");
  }finally{await context.setOffline(false);}
  await tray.locator("[data-test-battery]").press("Enter");
  await expect(net).toHaveCount(0);
  const battery=tray.locator("[data-test-battery-popup]");
  await expect(battery.locator("[data-test-battery-percent]")).toHaveText("73%");
  const meter=battery.locator("[data-test-battery-meter]");
  await expect(meter).toHaveCSS("width","32px");
  await expect(meter).toHaveCSS("height","32px");
  await expect(meter).toHaveCSS("background-position-x","-224px");
  await expect(meter).toHaveCSS("background-image",/battery-meter\.66984ffe\.webp/);
  await expect(battery.getByRole("status")).toContainText("73% remaining");
  await expect(battery.locator("[data-test-battery-plug]")).toHaveCount(0);
  const setBattery=async(level:number,charging:boolean)=>page.evaluate(({level,charging})=>{
    const manager=(window as unknown as {__sourceTestBattery:EventTarget&{level:number;charging:boolean}}).__sourceTestBattery;
    Object.assign(manager,{level,charging});
    manager.dispatchEvent(new Event("levelchange"));
    manager.dispatchEvent(new Event("chargingchange"));
  },{level,charging});
  await setBattery(.099,false);
  await expect(meter).toHaveCSS("background-position-x","-640px");
  await expect(battery.locator("[data-test-battery-percent]")).toHaveText("10%");
  await setBattery(.1,true);
  await expect(meter).toHaveCSS("background-position-x","-352px");
  await expect(battery.locator("[data-test-battery-plug]")).toHaveCSS("background-position-x","-960px");
  await expect(battery.getByRole("status")).toContainText("plugged in, charging");
  await setBattery(1,true);
  await expect(battery.getByRole("status")).toContainText("Fully charged (100%)");
  await setBattery(NaN,false);
  await expect(battery.locator("[data-test-battery-percent]")).toHaveText("Unavailable");
  await expect(meter).toHaveCount(0);
  await setBattery(.73,false);
  await expect(meter).toHaveCSS("background-position-x","-224px");
  await battery.getByRole("radio",{name:"Power saver"}).check();
  await expect(shell).toHaveCSS("filter","brightness(0.6)");
  await battery.getByRole("radio",{name:"Balanced"}).check();
  await expect(shell).toHaveCSS("filter","none");
  const volume=tray.locator("[data-test-volume]");
  await volume.press("Enter");
  await expect(battery).toHaveCount(0);
  const mixer=tray.locator("[data-test-volume-popup]");
  await mixer.getByRole("slider").fill("40");
  await expect(volume.locator("img")).toHaveAttribute("src",/volume-32\.1859a18f\.webp/);
  await mixer.getByRole("button",{name:"Mute system"}).click();
  await expect(mixer.getByRole("slider")).toBeDisabled();
  await page.keyboard.press("Escape");
  await expect(mixer).toHaveCount(0);
  await expect(volume).toBeFocused();
  await tray.locator("[data-test-datetime-trigger]").click();
  const calendar=tray.locator("[data-test-datetime-popup]");
  await expect(calendar).toBeVisible();
  await expect(calendar).toHaveCSS("border-top-left-radius","7px");
  await expect(calendar).toHaveCSS("background-image",/linear-gradient/);
  await expect(calendar.locator("[data-test-source-analog-clock] svg")).toHaveCSS("width","128px");
  await expect(calendar.locator("[data-test-source-digital-seconds]")).toBeVisible();
  const bounds=(await calendar.boundingBox())!,bar=(await shell.locator(".windows-taskbar").boundingBox())!;
  expect(bounds.y+bounds.height).toBeLessThanOrEqual(bar.y+2);
  expect(bounds.x).toBeGreaterThanOrEqual(-2);
  await calendar.getByRole("button",{name:"Next month"}).click();
  await calendar.getByRole("button",{name:"Choose month"}).click();
  await expect(calendar.getByRole("button",{name:"Jan",exact:true})).toBeVisible();
  await calendar.getByRole("button",{name:"Jan",exact:true}).click();
  await expect(calendar.getByRole("button",{name:"Choose month"})).toHaveText("January");
  await center.press("Enter");
  await expect(calendar).toHaveCount(0);
  await summary.locator("[data-test-open-action-center]").click();
  await expect(page.locator('[data-test-window="cpanel"]').last().locator("[data-test-cpanel-action-center]")).toBeVisible();
});

for(const theme of ["aero-1","aero-2","aero-3","aero-4","basic-1"] as const){
  test(theme+" uses interactive Win7 tray and original calendar skin",async({page})=>{
    await page.goto("/?theme="+theme);
    await page.locator('[data-test-avatar="win7"]').click({timeout:12000});
    const tray=page.locator('[data-test-taskbar-tray="'+theme+'"]');
    const clock=tray.locator("[data-test-datetime-trigger]");
    await clock.click();
    const popup=tray.locator("[data-test-datetime-popup]");
    await expect(popup).toBeVisible();
    await expect(popup).toHaveCSS("border-top-left-radius",theme==="basic-1"?"0px":"7px");
    if(theme==="basic-1")await expect(popup).toHaveCSS("box-shadow","none");
    await expect(popup.locator(".source-macos-calendar-days .is-today")).toHaveCSS("border-top-style","dotted");
    await expect(popup.locator("[data-test-source-analog-clock] svg")).toHaveCSS("background-color","rgb(224, 230, 233)");
    await page.keyboard.press("Escape");
    await expect(popup).toHaveCount(0);
    await expect(clock).toBeFocused();
  });
}

for(const [theme,surface,textColor,accent] of [
  ["basic-2","rgb(212, 208, 200)","rgb(0, 0, 0)","rgb(10, 36, 106)"],
  ["basic-3","rgb(0, 0, 0)","rgb(255, 255, 255)","rgb(128, 0, 128)"],
  ["basic-4","rgb(255, 255, 255)","rgb(0, 0, 0)","rgb(0, 0, 0)"]
] as const){
  test(theme+" classic opaque tray, calendar selection and keyboard lifecycle",async({page})=>{
    await page.goto("/?theme="+theme);
    await page.locator('[data-test-avatar="win7"]').click({timeout:12000});
    const shell=page.locator('[data-test-main-screen][data-theme="'+theme+'"]');
    const tray=shell.locator('[data-test-taskbar-tray="'+theme+'"]');
    const clock=tray.locator("[data-test-datetime-trigger]");
    await clock.click();
    const popup=tray.locator("[data-test-datetime-popup]");
    await expect(popup).toBeVisible();
    await expect(popup).toHaveCSS("background-color",surface);
    await expect(popup).toHaveCSS("color",textColor);
    await expect(popup).toHaveCSS("border-top-left-radius","0px");
    await expect(popup).toHaveCSS("box-shadow","none");
    await expect(popup).toHaveCSS("backdrop-filter","none");
    await expect(popup.locator(".source-macos-calendar header")).toHaveCSS("background-color",accent);
    const today=popup.locator(".source-macos-calendar-days .is-today");
    await expect(today).toHaveCSS("background-color",accent);
    await expect(today).toHaveCSS("outline-style","dotted");
    await expect(popup.locator("[data-test-source-analog-clock] svg")).toHaveCSS("background-color","rgb(224, 230, 233)");
    await popup.getByRole("button",{name:"Next month"}).click();
    await popup.getByRole("button",{name:"Choose year"}).click();
    await expect(popup.locator('.source-macos-calendar-picker[aria-label="Years"]')).toBeVisible();
    await popup.getByRole("button",{name:"Previous years"}).click();
    await popup.getByRole("button",{name:"Next years"}).click();
    await clock.press("Escape");
    await expect(popup.locator('.source-macos-calendar-picker[aria-label="Years"]')).toHaveCount(0);
    await clock.press("Escape");
    await expect(popup).toHaveCount(0);
    const volume=tray.locator("[data-test-volume]");
    await volume.press("Enter");
    const mixer=tray.locator("[data-test-volume-popup]");
    await expect(mixer).toHaveCSS("background-color",surface);
    await mixer.getByRole("slider").fill("45");
    await expect(mixer.getByRole("slider")).toHaveValue("45");
    await mixer.getByRole("button",{name:"Mute system"}).click();
    await expect(mixer.getByRole("slider")).toBeDisabled();
    await clock.press("Enter");
    await expect(mixer).toHaveCount(0);
    await expect(popup).toBeVisible();
  });
}

test("Win7 hidden tray keeps actual components mounted, closes on Escape and customizes",async({page})=>{
  await page.goto("/?theme=win7");
  await page.locator('[data-test-avatar="win7"]').click({timeout:12000});
  await page.locator(".windows-taskbar__running").click({button:"right",position:{x:15,y:5}});
  await page.locator('[data-test-taskbar-context-action="properties"]').click();
  await page.locator('[data-test-taskbar-settings-customize]').click();
  const cpanel=page.locator('[data-test-window="cpanel"]').last();
  const settings=cpanel.locator("[data-test-cpanel-notification]");
  await expect(settings).toBeVisible();
  await settings.locator('[data-test-cpanel-notification-icon="TaskbarVolume"] select').selectOption("hidden");
  await settings.locator('[data-test-cpanel-notification-icon="TaskbarNetwork"] select').selectOption("notifications-only");
  await settings.getByRole("button",{name:"OK",exact:true}).click();
  const tray=page.locator('[data-test-taskbar-tray="win7"]');
  const toggle=tray.locator("[data-test-tray-hidden-toggle]");
  await expect(toggle).toBeVisible();
  await expect(tray.locator("[data-test-volume]")).toHaveCount(0);
  await toggle.click();
  const hidden=tray.locator("[data-test-tray-hidden-items]");
  await expect(hidden).toBeVisible();
  await expect(hidden.locator("[data-test-tray-hidden-icon]")).toHaveCount(2);
  const volume=hidden.locator("[data-test-volume]");
  await volume.click();
  const mixer=hidden.locator("[data-test-volume-popup]");
  await expect(mixer).toBeVisible();
  await mixer.getByRole("slider").fill("35");
  await expect(mixer.getByRole("slider")).toHaveValue("35");
  await page.keyboard.press("Escape");
  await expect(mixer).toHaveCount(0);
  await expect(volume).toBeFocused();
  await page.keyboard.press("Escape");
  await expect(hidden).toHaveCount(0);
  await expect(toggle).toBeFocused();
  await toggle.click();
  await hidden.locator("[data-test-network]").click();
  await expect(hidden.locator("[data-test-network-popup]")).toBeVisible();
  await tray.locator("[data-test-datetime-trigger]").click();
  await expect(hidden).toHaveCount(0);
  await expect(tray.locator("[data-test-datetime-popup]")).toBeVisible();
  await toggle.click();
  await hidden.locator("[data-test-tray-customize]").click();
  await expect(hidden).toHaveCount(0);
  await expect(page.locator('[data-test-window="cpanel"]').last().locator("[data-test-cpanel-notification]")).toBeVisible();
});
