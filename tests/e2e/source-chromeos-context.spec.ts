import {test,expect,type Locator} from "@playwright/test";
async function paint(menu:Locator){
  await expect(menu).toBeVisible();
  await expect(menu).toHaveCSS("background-color","rgb(255, 255, 255)");
  await expect(menu).toHaveCSS("border-top-left-radius","2px");
  await expect(menu).toHaveCSS("width","200px");
}
test("ChromeOS inherited desktop selection and original menu palette across surfaces",async({page})=>{
  await page.goto("/?theme=chromeos");
  await page.locator('[data-test-avatar="win7"]').click({timeout:12000});
  const desktop=page.locator("#desktop-icons");
  const icon=desktop.locator('[data-test-desktop-icon="computer"]');
  await icon.click();
  await expect(icon).toHaveClass(/is-active/);
  await expect(icon).toHaveCSS("background-color","rgba(0, 0, 0, 0.267)");
  await desktop.click({button:"right",position:{x:260,y:200}});
  const root=desktop.locator("[data-test-desktop-menu]");
  await paint(root);
  const refresh=root.getByRole("menuitem",{name:"Refresh"});
  await refresh.hover();
  await expect(refresh).toHaveCSS("background-color","rgba(0, 0, 0, 0.067)");
  await page.keyboard.press("Escape");
  await expect(root).toHaveCount(0);
  await icon.dblclick();
  const win=page.locator('[data-test-window="computer"]').last();
  await expect(win).toBeVisible();
  const content=win.locator(".explorer-content");
  const bounds=await content.boundingBox();
  await content.click({button:"right",position:{x:Math.max(10,bounds!.width-12),y:Math.max(10,bounds!.height-12)}});
  const menu=win.locator('[data-test-explorer-context="background"]');
  await paint(menu);
  const view=menu.locator("[data-test-explorer-context-view]");
  await view.click();
  const child=menu.locator("[data-test-explorer-background-submenu]");
  await paint(child);
  const box=await child.boundingBox();
  expect(box!.x).toBeGreaterThanOrEqual(0);
  expect(box!.x+box!.width).toBeLessThanOrEqual(page.viewportSize()!.width+1);
  await page.keyboard.press("Escape");
  await expect(menu).toHaveCount(0);
  await win.locator('[data-source-window-control="close"]').click();
  await page.locator("[data-test-start-button]").click();
  const launcher=page.locator("[data-test-chromeos-launcher]");
  await launcher.locator("[data-test-start-search]").fill("Notepad");
  await launcher.locator('[data-test-program="notepad"]').click({button:"right"});
  const popup=page.locator('body > [data-test-start-program-context="notepad"]');
  await paint(popup);
  await popup.locator('[data-test-start-context-action="open"]').click();
  await expect(page.locator('[data-test-window="notepad"]')).toBeVisible();
  const task=page.locator('[data-test-taskbar-running-group="notepad"],[data-test-taskbar-pin="notepad"]').first();
  await task.click({button:"right"});
  await paint(page.locator('[data-test-taskbar-context="item"]'));
  await page.keyboard.press("Escape");
});
