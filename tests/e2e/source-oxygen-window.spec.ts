import {test,expect} from "@playwright/test";
test("Oxygen WindowMain uses source circular gradient controls and shared lifecycle",async({page})=>{
  await page.goto("/?theme=oxygen");
  await page.locator('[data-test-source-logon-avatar="oxygen"]').click({timeout:12000});
  const shell=page.locator('[data-test-main-screen][data-theme="oxygen"]');
  await shell.locator('[data-test-desktop-icon="computer"]').dblclick();
  const win=shell.locator('[data-test-window="computer"]');
  await expect(win).toBeVisible();
  await expect(win).toHaveCSS("background-color","rgb(49, 54, 59)");
  await expect(win).toHaveCSS("border-top-color","rgb(71, 76, 85)");
  await expect(win).toHaveCSS("border-top-left-radius","4px");
  await expect(win.locator(".windows-window__body")).toHaveCSS("background-color","rgb(42, 46, 50)");
  const close=win.locator('[data-source-window-control="close"]');
  await expect(close).toHaveCSS("width","20px");
  await expect(close).toHaveCSS("height","20px");
  await expect(close).toHaveCSS("border-top-left-radius","50%");
  await expect(close).toHaveCSS("margin-inline-end","10px");
  await expect(close).toHaveCSS("background-image",/linear-gradient/);
  await close.hover();
  await expect(close).toHaveCSS("color","rgb(218, 68, 83)");
  await win.locator('[data-source-window-control="maximize"]').click();
  await expect(win).toHaveCSS("border-top-left-radius","0px");
  await win.locator('[data-source-window-control="restore"]').click();
  await expect(win).toHaveCSS("border-top-left-radius","4px");
  await win.locator('[data-source-window-control="minimize"]').click();
  await expect(win).toHaveCount(0);
  await shell.locator('[data-test-taskbar-pin="computer"],[data-test-taskbar-running-group="computer"]').first().click();
  await expect(win).toBeVisible();
  await close.click();
  await expect(win).toHaveCount(0);
});
