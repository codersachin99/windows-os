import {test,expect} from "@playwright/test";
test("Ubuntu top bar and vertical dock use original geometry and real windows",async({page})=>{
  await page.goto("/?theme=ubuntu");
  await page.locator('[data-test-source-logon-avatar="ubuntu"]').click({timeout:12000});
  const shell=page.locator('[data-test-main-screen][data-theme="ubuntu"]');
  const bar=shell.locator('[data-test-taskbar="ubuntu"]');
  const dock=shell.locator("[data-test-dock]");
  await expect(bar).toHaveCSS("height","32px");
  await expect(bar).toHaveCSS("background-color","rgb(19, 19, 19)");
  await expect(dock).toHaveCSS("width","64px");
  expect((await dock.boundingBox())!.y).toBe(32);
  expect((await shell.locator("#desktop").boundingBox())!.x).toBe(64);
  await shell.locator('[data-test-desktop-icon="computer"]').dblclick();
  const win=shell.locator('[data-test-window="computer"]');
  await expect(win).toBeVisible();
  const item=dock.locator('[data-source-ubuntu-dock-id="computer"]');
  await expect(item).toHaveClass(/is-running/);
  await expect(item.locator("img")).toHaveCSS("width","36px");
  await win.locator('[data-source-window-control="minimize"]').click();
  await expect(win).toHaveCount(0);
  await item.click();
  await expect(win).toBeVisible();
  await win.locator('[data-source-window-control="maximize"]').click();
  expect((await win.boundingBox())!.x).toBe(64);
  expect((await win.boundingBox())!.y).toBe(32);
  await dock.locator("[data-test-start-button]").click();
  await expect(shell.locator("[data-test-start-menu]")).toBeVisible();
  await bar.locator("[data-test-activities-button]").click();
  await expect(shell.locator("[data-test-start-menu]")).toHaveCount(0);
});
