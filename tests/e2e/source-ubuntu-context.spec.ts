import {test,expect,type Locator} from "@playwright/test";
async function paint(menu:Locator){
  await expect(menu).toBeVisible();
  await expect(menu).toHaveCSS("background-color","rgb(29, 29, 29)");
  await expect(menu).toHaveCSS("border-top-left-radius","10px");
  await expect(menu).toHaveCSS("border-top-color","rgb(75, 75, 75)");
}
test("Ubuntu desktop paints selected artwork and original WinUI menus across surfaces",async({page})=>{
  await page.goto("/?theme=ubuntu");
  await page.locator('[data-test-source-logon-avatar="ubuntu"]').click({timeout:12000});
  const desktop=page.locator("#desktop-icons");
  const icon=desktop.locator('[data-test-desktop-icon="computer"]');
  await icon.click();
  await expect(icon).toHaveClass(/is-active/);
  await expect(icon).toHaveCSS("background-color","rgba(0, 0, 0, 0)");
  await expect(icon.locator(".desktop__icon-icon")).toHaveCSS("background-color","rgb(240, 184, 91)");
  await expect(icon.locator(".desktop__icon-name")).toHaveCSS("border-top-left-radius","5px");
  const area=(await desktop.boundingBox())!;
  await desktop.click({button:"right",position:{x:Math.min(260,area.width-12),y:Math.min(200,area.height-12)}});
  const root=desktop.locator("[data-test-desktop-menu]");
  await paint(root);
  const refresh=root.getByRole("menuitem",{name:"Refresh",exact:true});
  await refresh.focus();
  await expect(refresh).toHaveCSS("background-color","rgb(62, 62, 62)");
  await root.locator("[data-test-desktop-view]").click();
  await paint(desktop.locator("[data-test-desktop-background-submenu]"));
  await page.keyboard.press("Escape");
  await expect(root).toHaveCount(0);
  await icon.dblclick();
  const win=page.locator('[data-test-window="computer"]').last();
  await expect(win).toBeVisible();
  const content=win.locator(".explorer-content");
  const bounds=(await content.boundingBox())!;
  await content.click({button:"right",position:{x:Math.max(10,bounds.width-12),y:Math.max(10,bounds.height-12)}});
  const menu=win.locator('[data-test-explorer-context="background"]');
  await paint(menu);
  await menu.locator("[data-test-explorer-context-view]").click();
  const child=menu.locator("[data-test-explorer-background-submenu]");
  await paint(child);
  const box=(await child.boundingBox())!;
  expect(box.x).toBeGreaterThanOrEqual(-2);
  expect(box.x+box.width).toBeLessThanOrEqual(page.viewportSize()!.width+2);
  await page.keyboard.press("Escape");
  await win.locator('[data-source-window-control="close"]').click();
  await page.locator("[data-test-activities-button]").click();
  const launcher=page.locator("[data-test-ubuntu-launchpad]");
  await launcher.locator("[data-test-start-search]").fill("Notepad");
  await launcher.locator('[data-test-program="notepad"]').click({button:"right"});
  const popup=page.locator('body > [data-test-start-program-context="notepad"]');
  await paint(popup);
  await popup.locator('[data-test-start-context-action="open"]').click();
  await expect(page.locator('[data-test-window="notepad"]')).toBeVisible();
});
