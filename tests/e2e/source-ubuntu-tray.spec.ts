import {test,expect} from "@playwright/test";
test("Ubuntu source tray shares exclusive popup state, calendar and system menu",async({page})=>{
  await page.goto("/?theme=ubuntu");
  await page.locator('[data-test-source-logon-avatar="ubuntu"]').click({timeout:12000});
  const tray=page.locator('[data-test-taskbar-tray="ubuntu"]');
  await expect(tray.locator("[data-test-tray-icon]")).toHaveCount(4);
  await expect(tray.locator("[data-test-tray-hidden-toggle]")).toHaveCount(0);
  await tray.locator("[data-test-volume]").click();
  const volume=tray.locator("[data-test-volume-popup]");
  await expect(volume).toBeVisible();
  await expect(volume).toHaveCSS("background-color","rgb(29, 29, 29)");
  await volume.getByRole("button",{name:"Mute system"}).click();
  await expect(volume.getByRole("button",{name:"Unmute system"})).toBeVisible();
  await tray.locator("[data-test-network]").click();
  await expect(volume).toHaveCount(0);
  await expect(tray.locator("[data-test-network-popup]")).toBeVisible();
  await tray.locator("[data-test-datetime-trigger]").click();
  await expect(tray.locator("[data-test-network-popup]")).toHaveCount(0);
  const calendar=tray.locator("[data-test-datetime-popup]");
  await expect(calendar).toBeVisible();
  await expect(calendar.locator("[data-test-source-analog-clock] svg")).toHaveCSS("width","140px");
  await calendar.getByRole("button",{name:"Next month"}).click();
  await tray.getByRole("button",{name:"System menu"}).click();
  await expect(calendar).toHaveCount(0);
  const menu=tray.getByRole("menu",{name:"System menu"});
  await expect(menu).toBeVisible();
  await expect(menu.getByRole("menuitem")).toHaveText(["Settings","About","Help and Support","Account","Log off","Restart","Shut down"]);
  await menu.getByRole("menuitem",{name:"Account",exact:true}).click();
  await expect(page.locator('[data-test-window="cpanel"]')).toBeVisible();
  await expect(menu).toHaveCount(0);
});
