import {test,expect} from "@playwright/test";
test("Ubuntu WindowMain has source frame, controls and lifecycle",async({page})=>{
  await page.goto("/?theme=ubuntu");
  await page.locator('[data-test-source-logon-avatar="ubuntu"]').click({timeout:12000});
  const shell=page.locator('[data-test-main-screen][data-theme="ubuntu"]');
  await shell.locator('[data-test-desktop-icon="computer"]').dblclick();
  const computer=shell.locator('[data-test-window="computer"]');
  await expect(computer).toBeVisible();
  await expect(computer).toHaveAttribute("data-source-window-active","true");
  await expect(computer).toHaveCSS("background-color","rgb(34, 34, 34)");
  await expect(computer).toHaveCSS("border-top-left-radius","15px");
  await expect(computer).toHaveCSS("border-top-color","rgb(17, 5, 11)");
  await expect(computer.locator(".windows-window__titlebar")).toHaveCSS("margin-top","5px");
  await expect(computer.locator(".windows-window__title")).toHaveCSS("font-weight","700");
  const minimize=computer.locator('[data-source-window-control="minimize"]');
  await expect(minimize).toHaveCSS("width","23px");
  await expect(minimize).toHaveCSS("height","23px");
  await expect(minimize).toHaveCSS("border-top-left-radius","50%");
  await expect(computer.locator('[data-source-window-control="close"]')).toHaveCSS("background-color","rgb(55, 55, 55)");
  const before=(await computer.boundingBox())!;
  expect(before.x).toBeGreaterThanOrEqual(64);
  expect(before.y).toBeGreaterThanOrEqual(32);
  expect(before.x+before.width).toBeLessThanOrEqual((page.viewportSize()!).width+1);
  expect(before.y+before.height).toBeLessThanOrEqual((page.viewportSize()!).height+1);
  await shell.locator("[data-test-activities-button]").click();
  const search=shell.locator("[data-test-ubuntu-launchpad]").getByRole("searchbox");
  await search.fill("Notepad");
  await search.press("Enter");
  const notepad=shell.locator('[data-test-window="notepad"]');
  await expect(notepad).toBeVisible();
  await expect(computer).toHaveCSS("background-color","rgb(44, 44, 44)");
  await notepad.locator('[data-source-window-control="close"]').click();
  await shell.locator('[data-source-ubuntu-dock-id="computer"]').click();
  await expect(computer).toHaveAttribute("data-source-window-active","true");
  await computer.locator('[data-source-window-control="maximize"]').click();
  await expect(computer).toHaveCSS("border-top-left-radius","0px");
  await computer.locator('[data-source-window-control="restore"]').click();
  await expect(computer).toHaveCSS("border-top-left-radius","15px");
  await minimize.click();
  await expect(computer).toHaveCount(0);
  await shell.locator('[data-source-ubuntu-dock-id="computer"]').click();
  await expect(computer).toBeVisible();
});
