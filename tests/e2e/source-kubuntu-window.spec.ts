import {test,expect} from "@playwright/test";
test("Kubuntu WindowMain source frame and circular controls retain Guest lifecycle",async({page})=>{
  await page.goto("/?theme=kubuntu");
  await page.locator('[data-test-source-logon-avatar="kubuntu"]').click({timeout:12000});
  const shell=page.locator('[data-test-main-screen][data-theme="kubuntu"]');
  await shell.locator('[data-test-desktop-icon="computer"]').dblclick();
  const computer=shell.locator('[data-test-window="computer"]');
  await expect(computer).toBeVisible();
  await expect(computer).toHaveAttribute("data-source-window-active","true");
  await expect(computer).toHaveCSS("background-color","rgb(49, 54, 59)");
  await expect(computer).toHaveCSS("border-top-color","rgb(79, 88, 95)");
  await expect(computer).toHaveCSS("border-top-left-radius","4px");
  await expect(computer.locator(".windows-window__body")).toHaveCSS("background-color","rgb(42, 46, 50)");
  const close=computer.locator('[data-source-window-control="close"]');
  const minimize=computer.locator('[data-source-window-control="minimize"]');
  await expect(close).toHaveCSS("background-color","rgb(218, 68, 83)");
  await expect(close).toHaveCSS("border-top-left-radius","50%");
  await expect(close).toHaveCSS("width","24px");
  await expect(close).toHaveCSS("height","24px");
  await expect(minimize).toHaveCSS("margin-inline-start","5px");
  await computer.locator('[data-source-window-control="maximize"]').click();
  await expect(computer).toHaveClass(/is-maximized/);
  await expect(computer).toHaveCSS("border-top-left-radius","0px");
  await computer.locator('[data-source-window-control="restore"]').click();
  await expect(computer).toHaveCSS("border-top-left-radius","4px");
  await minimize.click();
  await expect(computer).toHaveCount(0);
  await shell.locator('[data-test-taskbar-pin="computer"],[data-test-taskbar-running-group="computer"]').first().click();
  await expect(computer).toBeVisible();
  await close.click();
  await expect(computer).toHaveCount(0);
});
