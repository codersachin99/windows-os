import {test,expect} from "@playwright/test";
test("Oxygen Start source list, recents, grouped search and Guest commands",async({page})=>{
  await page.goto("/?theme=oxygen");
  await page.locator('[data-test-source-logon-avatar="oxygen"]').click({timeout:12000});
  const start=page.locator("[data-test-start-button]");
  await start.click();
  const menu=page.locator("[data-test-oxygen-start]");
  await expect(menu).toBeVisible();
  await expect(menu).toHaveCSS("border-top-left-radius","6px");
  await expect(menu).toHaveCSS("border-top-color","rgb(71, 76, 85)");
  await expect(menu).toHaveCSS("background-image",/linear-gradient/);
  await expect(menu.getByRole("button",{name:"Guest account"}).locator("img")).toHaveAttribute("src","/assets/images/guest.1a7eab2b.webp");
  await expect(menu.locator(".source-kubuntu-start-body")).toHaveCSS("height","320px");
  const list=menu.locator("[data-test-start-menu-all]");
  await expect(list.locator('[data-test-program="notepad"] img')).toHaveAttribute("width","32");
  await expect(list.locator('[data-test-program="notepad"] img')).toHaveAttribute("src","/assets/images/notepad-oxygen.9f263926.webp");
  const search=menu.getByRole("searchbox");
  await expect(search).toHaveAttribute("placeholder","Search programs");
  await search.fill("Notepad");
  await expect(menu.locator('[data-test-start-group="apps"] [data-test-program="notepad"]')).toBeVisible();
  await search.press("Enter");
  await expect(page.locator('[data-test-window="notepad"]')).toBeVisible();
  await expect(menu).toHaveCount(0);
  await start.click();
  await expect(menu.locator('[data-test-recent-program="notepad"] img')).toHaveAttribute("width","48");
  await search.fill("Display");
  await menu.locator('[data-test-start-group="settings"]').getByRole("button",{name:"Display",exact:true}).click();
  await expect(page.locator('[data-test-window="cpanel"]')).toBeVisible();
  await start.click();
  await menu.getByRole("button",{name:"Documents",exact:true}).click();
  await expect(page.locator('[data-test-window="computer"]')).toBeVisible();
  await start.click();
  await menu.getByRole("button",{name:"Log off",exact:true}).click();
  await expect(page.locator('[data-test-logon-screen]')).toBeVisible();
});
