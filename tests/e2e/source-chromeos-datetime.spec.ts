import {test,expect} from "@playwright/test";
test("ChromeOS DateTime opens the source calendar and live analog/digital clocks",async({page})=>{
  await page.clock.install({time:new Date(2026,10,24,15,30,45)});
  await page.goto("/?theme=chromeos");
  await page.locator('[data-test-avatar="win7"]').click({timeout:12000});
  const trigger=page.locator("[data-test-datetime-trigger]");
  await expect(trigger.locator("time span").first()).toHaveText("15:30");
  await expect(trigger.locator("time span").last()).toBeHidden();
  await trigger.click();
  const popup=page.locator("[data-test-datetime-popup]");
  await expect(popup).toBeVisible();
  await expect(popup.locator("[data-test-source-analog-clock]")).toBeVisible();
  await expect(popup.locator("[data-test-source-digital-seconds]")).toHaveText(/^15:30:\d{2}$/);
  await expect(popup.locator('[data-test-clock-hand="hour"]')).toHaveAttribute("transform","rotate(105 64 64)");
  const digital=popup.locator("[data-test-source-digital-seconds]");
  const before=await digital.textContent();
  await page.clock.runFor(1000);
  await expect(digital).not.toHaveText(before!);
  await expect(popup.locator("[data-test-macos-calendar-day]")).toHaveCount(42);
  await popup.getByRole("button",{name:"Next month"}).click();
  await expect(popup.getByRole("button",{name:"Choose month"})).toHaveText("December");
  await popup.locator(".source-macos-calendar-today").click();
  await expect(popup.getByRole("button",{name:"Choose month"})).toHaveText("November");
  await expect(popup.getByRole("button",{name:/Change date and time settings/})).toBeDisabled();
  await page.locator("[data-test-network]").press("Enter");
  await expect(popup).toHaveCount(0);
  await expect(page.locator("[data-test-network-popup]")).toBeVisible();
  await page.keyboard.press("Escape");
});
