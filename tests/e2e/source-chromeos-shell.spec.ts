import {expect,test} from "@playwright/test";
test("ChromeOS original shelf and WindowMain follow real Guest window lifecycle",async({page})=>{
  await page.goto("/?theme=chromeos");
  await page.locator('[data-test-avatar="win7"]').click({timeout:12000});
  const shell=page.locator('[data-test-main-screen]');
  await expect(shell).toHaveAttribute("data-theme","chromeos");
  const shelf=shell.locator("[data-test-taskbar]");
  await expect(shelf).toHaveCSS("height","48px");
  await expect(shelf).toHaveCSS("background-color","rgba(245, 250, 255, 0.95)");
  await expect(shelf).toHaveCSS("border-top-left-radius","24px");
  await expect(shelf.locator("[data-test-start-button]")).toHaveCSS("width","36px");
  await expect(shelf.locator("[data-test-tray-clock] time span").last()).toBeHidden();
  await shell.locator('[data-test-desktop-icon="computer"]').dblclick();
  const win=shell.locator('[data-test-window="computer"]');
  await expect(win).toBeVisible();
  await expect(win.locator(".windows-window__titlebar")).toHaveCSS("background-color","rgb(37, 79, 174)");
  await expect(win.locator(".windows-window__title")).toBeHidden();
  const max=win.locator('[data-source-window-control="maximize"]');
  await expect(max).toHaveCSS("width","28px");
  const app=shelf.locator(".windows-taskbar__application.is-active");
  await expect(app).toBeVisible();
  await expect(app.locator("img")).toHaveCSS("width","36px");
  await max.click();
  await expect(win).toHaveClass(/is-maximized/);
  await expect(shelf).toHaveCSS("border-top-left-radius","0px");
  await win.locator('[data-source-window-control="restore"]').click();
  await expect(shelf).toHaveCSS("border-top-left-radius","24px");
  await win.locator('[data-source-window-control="minimize"]').click();
  await expect(win).toHaveCount(0);
  const running=shelf.locator('[data-test-taskbar-running-group="computer"],[data-test-taskbar-pin="computer"]').first();
  await running.click();
  await expect(win).toBeVisible();
  await win.locator('[data-source-window-control="close"]').click();
  await expect(win).toHaveCount(0);
});
